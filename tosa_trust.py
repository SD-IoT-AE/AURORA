
"""
AURORA - Dynamic UAV Trust Assessment
=====================================

Module:
    Telemetry and Operational State Assessment (TOSA)

Purpose:
    Maintain temporal trust estimates for UAV participants,
    calculate behavioral risk, and provide trust-based
    eligibility information to RFLD and ACRO.

Trust update:
    T_i(t) = alpha * T_i(t-1)
             + (1-alpha) * b_i(t)

Risk estimation:
    R_i(t) = 1 - T_i(t)

Behavioral reliability:
    b_i(t) = 1 - p_i(t)

where p_i(t) is the malicious-behavior probability
produced by the behavioral classification ensemble.

Default settings:
    alpha = 0.70
    trust_threshold = 0.50
    low_risk_threshold = 0.30
    high_risk_threshold = 0.70
    isolation_windows = 3

All trust and risk scores are normalized to [0, 1].

This module does not train the behavioral classifier.
It consumes classifier probabilities generated by
the AURORA detection models.

No manuscript experimental results are hard-coded.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from math import isfinite
from typing import Dict, List, Optional


class RiskLevel(str, Enum):
    """Operational risk categories."""

    LOW = "low"
    MODERATE = "moderate"
    HIGH = "high"


@dataclass(frozen=True)
class TrustConfig:
    """Configuration of the dynamic trust mechanism."""

    alpha: float = 0.70
    initial_trust: float = 1.0

    trust_threshold: float = 0.50

    low_risk_threshold: float = 0.30
    high_risk_threshold: float = 0.70

    isolation_windows: int = 3

    def __post_init__(self) -> None:

        probability_fields = (
            "alpha",
            "initial_trust",
            "trust_threshold",
            "low_risk_threshold",
            "high_risk_threshold",
        )

        for name in probability_fields:
            value = getattr(self, name)

            if not isfinite(value):
                raise ValueError(
                    f"{name} must be finite."
                )

            if not 0.0 <= value <= 1.0:
                raise ValueError(
                    f"{name} must be between 0 and 1."
                )

        if (
            self.low_risk_threshold
            >= self.high_risk_threshold
        ):
            raise ValueError(
                "Low-risk threshold must be smaller "
                "than high-risk threshold."
            )

        if self.isolation_windows < 1:
            raise ValueError(
                "isolation_windows must be >= 1."
            )


@dataclass(frozen=True)
class TrustObservation:
    """Result of one UAV trust-assessment update."""

    uav_id: int
    timestamp: float

    malicious_probability: float
    behavioral_score: float

    previous_trust: float
    trust: float
    risk: float

    risk_level: RiskLevel

    eligible_for_fl: bool

    consecutive_high_risk: int
    isolation_recommended: bool


@dataclass
class UAVTrustState:
    """Internal state maintained for one UAV."""

    trust: float

    consecutive_high_risk: int = 0

    last_timestamp: Optional[float] = None

    history: List[TrustObservation] = field(
        default_factory=list
    )


class TrustManager:
    """
    Stateful trust manager for UAV participants.

    Each UAV maintains an independent trust history.

    The trust manager does not directly enforce
    mitigation actions. It exposes risk and isolation
    recommendations to the ACRO policy engine.
    """

    def __init__(
        self,
        config: Optional[TrustConfig] = None,
    ) -> None:

        self.config = config or TrustConfig()

        self._states: Dict[int, UAVTrustState] = {}

    @staticmethod
    def _validate_probability(
        value: float,
        name: str,
    ) -> float:

        value = float(value)

        if not isfinite(value):
            raise ValueError(
                f"{name} must be finite."
            )

        if not 0.0 <= value <= 1.0:
            raise ValueError(
                f"{name} must be between 0 and 1."
            )

        return value

    def register_uav(
        self,
        uav_id: int,
        initial_trust: Optional[float] = None,
    ) -> None:
        """
        Register a UAV with an initial trust value.

        Registration is idempotent: an existing UAV
        state is not overwritten.
        """

        if uav_id in self._states:
            return

        trust = (
            self.config.initial_trust
            if initial_trust is None
            else self._validate_probability(
                initial_trust,
                "initial_trust",
            )
        )

        self._states[uav_id] = UAVTrustState(
            trust=trust
        )

    def update_from_probability(
        self,
        uav_id: int,
        malicious_probability: float,
        timestamp: float,
    ) -> TrustObservation:
        """
        Update UAV trust from classifier output.

        Parameters
        ----------
        uav_id:
            Identifier of the assessed UAV.

        malicious_probability:
            Classifier-estimated probability that
            the observed behavior is malicious.

        timestamp:
            Observation time in seconds.

        Returns
        -------
        TrustObservation:
            Updated trust, risk, eligibility,
            and isolation recommendation.
        """

        malicious_probability = (
            self._validate_probability(
                malicious_probability,
                "malicious_probability",
            )
        )

        timestamp = float(timestamp)

        if not isfinite(timestamp):
            raise ValueError(
                "timestamp must be finite."
            )

        self.register_uav(uav_id)

        state = self._states[uav_id]

        if (
            state.last_timestamp is not None
            and timestamp <= state.last_timestamp
        ):
            raise ValueError(
                "Trust observations must have "
                "strictly increasing timestamps "
                "for each UAV."
            )

        behavioral_score = (
            1.0 - malicious_probability
        )

        previous_trust = state.trust

        alpha = self.config.alpha

        updated_trust = (
            alpha * previous_trust
            + (1.0 - alpha) * behavioral_score
        )

        updated_trust = min(
            1.0,
            max(0.0, updated_trust),
        )

        risk = 1.0 - updated_trust

        risk_level = self.classify_risk(risk)

        if risk_level == RiskLevel.HIGH:
            state.consecutive_high_risk += 1
        else:
            state.consecutive_high_risk = 0

        eligible_for_fl = (
            updated_trust
            >= self.config.trust_threshold
        )

        isolation_recommended = (
            state.consecutive_high_risk
            >= self.config.isolation_windows
        )

        observation = TrustObservation(
            uav_id=uav_id,
            timestamp=timestamp,
            malicious_probability=(
                malicious_probability
            ),
            behavioral_score=behavioral_score,
            previous_trust=previous_trust,
            trust=updated_trust,
            risk=risk,
            risk_level=risk_level,
            eligible_for_fl=eligible_for_fl,
            consecutive_high_risk=(
                state.consecutive_high_risk
            ),
            isolation_recommended=(
                isolation_recommended
            ),
        )

        state.trust = updated_trust
        state.last_timestamp = timestamp

        state.history.append(observation)

        return observation

    def update_from_behavior(
        self,
        uav_id: int,
        behavioral_score: float,
        timestamp: float,
    ) -> TrustObservation:
        """
        Update trust using an already computed
        behavioral reliability score.

        b_i(t) = 1 - p_i(t)
        """

        behavioral_score = (
            self._validate_probability(
                behavioral_score,
                "behavioral_score",
            )
        )

        return self.update_from_probability(
            uav_id=uav_id,
            malicious_probability=(
                1.0 - behavioral_score
            ),
            timestamp=timestamp,
        )

    def classify_risk(
        self,
        risk: float,
    ) -> RiskLevel:
        """Classify a normalized risk score."""

        risk = self._validate_probability(
            risk,
            "risk",
        )

        if risk < self.config.low_risk_threshold:
            return RiskLevel.LOW

        if risk < self.config.high_risk_threshold:
            return RiskLevel.MODERATE

        return RiskLevel.HIGH

    def get_trust(
        self,
        uav_id: int,
    ) -> float:
        """Return the current UAV trust value."""

        self.register_uav(uav_id)

        return self._states[uav_id].trust

    def get_risk(
        self,
        uav_id: int,
    ) -> float:
        """Return the current UAV risk value."""

        return 1.0 - self.get_trust(uav_id)

    def is_eligible_for_fl(
        self,
        uav_id: int,
    ) -> bool:
        """
        Determine eligibility for federated learning
        using the configured trust threshold.
        """

        return (
            self.get_trust(uav_id)
            >= self.config.trust_threshold
        )

    def should_isolate(
        self,
        uav_id: int,
    ) -> bool:
        """
        Return whether the UAV has accumulated
        enough consecutive high-risk observations.
        """

        self.register_uav(uav_id)

        state = self._states[uav_id]

        return (
            state.consecutive_high_risk
            >= self.config.isolation_windows
        )

    def get_history(
        self,
        uav_id: int,
    ) -> List[TrustObservation]:
        """Return a copy of the UAV trust history."""

        self.register_uav(uav_id)

        return list(
            self._states[uav_id].history
        )

    def get_all_trust_values(
        self,
    ) -> Dict[int, float]:
        """Return current trust values for all UAVs."""

        return {
            uav_id: state.trust
            for uav_id, state in self._states.items()
        }

    def get_eligible_clients(
        self,
    ) -> List[int]:
        """Return UAV IDs eligible for FL participation."""

        return sorted(
            uav_id
            for uav_id in self._states
            if self.is_eligible_for_fl(uav_id)
        )

    def trust_stability(
        self,
        uav_id: Optional[int] = None,
    ) -> float:
        """
        Calculate temporal trust stability.

        TS = (1 - mean(|T(t)-T(t-1)|)) * 100

        For all UAVs, the calculation uses the
        pooled transitions from their histories.

        Returns 100% when no trust transitions
        are available.
        """

        if uav_id is None:
            states = list(self._states.values())
        else:
            self.register_uav(uav_id)
            states = [self._states[uav_id]]

        differences = []

        for state in states:

            values = [
                observation.trust
                for observation in state.history
            ]

            for index in range(1, len(values)):
                differences.append(
                    abs(
                        values[index]
                        - values[index - 1]
                    )
                )

        if not differences:
            return 100.0

        mean_difference = (
            sum(differences) / len(differences)
        )

        return 100.0 * (1.0 - mean_difference)

    def reset_uav(
        self,
        uav_id: int,
    ) -> None:
        """Reset one UAV to its initial trust state."""

        self._states[uav_id] = UAVTrustState(
            trust=self.config.initial_trust
        )

    def reset_all(self) -> None:
        """Remove all registered UAV trust states."""

        self._states.clear()


