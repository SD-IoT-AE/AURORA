    config = TrustConfig(
        alpha=0.70,
        initial_trust=1.0,
        trust_threshold=0.50,
        low_risk_threshold=0.30,
        high_risk_threshold=0.70,
        isolation_windows=3,
    )

    manager = TrustManager(config)

    malicious_probabilities = [
        0.10,
        0.20,
        0.85,
        0.95,
        0.98,
        0.99,
        0.99,
        0.99,
    ]

    print("AURORA Dynamic Trust Assessment")
    print("-" * 80)

    for t, probability in enumerate(
        malicious_probabilities,
        start=1,
    ):

        result = manager.update_from_probability(
            uav_id=1,
            malicious_probability=probability,
            timestamp=float(t),
        )

        print(
            f"t={t:02d} | "
            f"P(malicious)={probability:.2f} | "
            f"Trust={result.trust:.4f} | "
            f"Risk={result.risk:.4f} | "
            f"Level={result.risk_level.value:8s} | "
            f"FL={result.eligible_for_fl} | "
            f"Isolation={result.isolation_recommended}"
        )

    print("-" * 80)

    print(
        "Trust Stability:",
        f"{manager.trust_stability(1):.2f}%"
    )
